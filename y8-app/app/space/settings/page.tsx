const SETTINGS_CONTRACT_KEY = 'y8_settings_contract';

// ── Toggle Card Component ────────────────────────────────────────────────────────
interface ToggleCardProps {
  icon: React.ReactNode;
  label: string;
  description: string;
  value: boolean;
  onChange: (v: boolean) => void;
  isPending?: boolean;
  color?: string;
}

function ToggleCard({ icon, label, description, value, onChange, isPending, color = '#f5c518' }: ToggleCardProps) {
  return (
    <div
      className={`bg-white rounded-2xl border-2 p-5 transition-all cursor-pointer hover:shadow-md ${
        value ? 'border-[#f5c518] shadow-sm' : 'border-slate-200'
      }`}
      onClick={() => !isPending && onChange(!value)}
    >
      <div className="flex items-start justify-between gap-4">
        <div className="flex items-start gap-3">
          <div
            className="w-10 h-10 rounded-xl flex items-center justify-center shrink-0 transition-colors"
            style={{ background: value ? `${color}20` : '#f1f5f9', color: value ? color : '#94a3b8' }}
          >
            {icon}
          </div>
          <div>
            <p className="font-semibold text-slate-900 text-sm">{label}</p>
            <p className="text-xs text-slate-500 mt-0.5 leading-relaxed">{description}</p>
          </div>
        </div>
        <div className="shrink-0">
          {isPending ? (
            <RefreshCw className="w-5 h-5 text-slate-400 animate-spin" />
          ) : value ? (
            <ToggleRight className="w-8 h-8" style={{ color }} />
          ) : (
            <ToggleLeft className="w-8 h-8 text-slate-300" />
          )}
        </div>
      </div>
    </div>
  );
}

// ── Main Settings Page ───────────────────────────────────────────────────────────────
export default function SettingsPage() {
  useEffect(() => { document.title = 'On-Chain Settings | Y8'; }, []);

  const { address, isConnected, chain } = useAccount();
  const [contractAddr, setContractAddr] = useState<Address>(UNDEPLOYED);
  const [localSettings, setLocalSettings] = useState({
    gpsEnabled: false, activeDriver: false, onlineStatus: true,
    notifications: true, privacyMode: false, darkMode: false,
  });
  const [isSaving, setIsSaving] = useState(false);
  const [deployHash, setDeployHash] = useState<`0x${string}` | undefined>();

  // Load saved contract address
  useEffect(() => {
    const saved = localStorage.getItem(SETTINGS_CONTRACT_KEY);
    if (saved) setContractAddr(saved as Address);
  }, []);

  // Read on-chain settings
  const { data: onChainSettings, refetch } = useY8Settings(
    address,
    contractAddr,
  );

  // Sync on-chain settings to local state
  useEffect(() => {
    if (onChainSettings) {
      setLocalSettings({
        gpsEnabled:    (onChainSettings as any).gpsEnabled    ?? false,
        activeDriver:  (onChainSettings as any).activeDriver  ?? false,
        onlineStatus:  (onChainSettings as any).onlineStatus  ?? true,
        notifications: (onChainSettings as any).notifications ?? true,
        privacyMode:   (onChainSettings as any).privacyMode   ?? false,
        darkMode:      (onChainSettings as any).darkMode      ?? false,
      });
    }
  }, [onChainSettings]);

  const { update, isPending: isUpdating } = useUpdateSettings(contractAddr);

  // Deploy contract
  const { deployContractAsync, isPending: isDeploying } = useDeployContract();
  const { isSuccess: deployConfirmed, data: deployReceipt } = useWaitForTransactionReceipt({ hash: deployHash });

  useEffect(() => {
    if (deployConfirmed && deployReceipt?.contractAddress) {
      const addr = deployReceipt.contractAddress as Address;
      setContractAddr(addr);
      localStorage.setItem(SETTINGS_CONTRACT_KEY, addr);
      toast.success(`Contract deployed at ${addr.slice(0,8)}…`);
    }
  }, [deployConfirmed, deployReceipt]);

  const handleDeploy = async () => {
    try {
      const hash = await deployContractAsync({
        abi: Y8_SETTINGS_ABI,
        bytecode: Y8_SETTINGS_BYTECODE,
        chainId: baseSepolia.id,
      });
      setDeployHash(hash);
      toast.loading('Deploying Y8Settings contract…', { id: 'deploy' });
    } catch (e: any) {
      toast.error(e.shortMessage || e.message || 'Deploy failed');
    }
  };

  const handleToggle = async (key: keyof typeof localSettings, value: boolean) => {
    const next = { ...localSettings, [key]: value };
    setLocalSettings(next);

    if (contractAddr === UNDEPLOYED) {
      toast('Deploy the contract first to save settings on-chain.', { icon: '⚠️' });
      return;
    }
    try {
      await update(next);
      toast.success('Settings saved on-chain ✓');
      await refetch();
    } catch (e: any) {
      toast.error(e.shortMessage || 'Transaction failed');
      setLocalSettings(localSettings); // revert
    }
  };

  const isDeployed = contractAddr !== UNDEPLOYED;
  const needsSepolia = chain?.id !== baseSepolia.id;

  return (
    <div className="space-y-8">
      {/* Header */}
      <div className="flex items-center gap-3">
        <Link href="/space" className="text-slate-400 hover:text-slate-600 text-sm">← Space</Link>
        <span className="text-slate-300">|</span>
        <div className="flex items-center gap-2">
          <Settings2 className="w-5 h-5 text-[#f5c518]" />
          <h1 className="text-2xl font-bold text-slate-900">On-Chain Settings</h1>
        </div>
      </div>

      {/* Contract Deploy Banner */}
      <div className={`rounded-2xl border-2 p-6 ${
        isDeployed
          ? 'bg-green-50 border-green-200'
          : 'bg-amber-50 border-amber-200'
      }`}>
        <div className="flex items-start justify-between gap-4 flex-wrap">
          <div>
            <div className="flex items-center gap-2 mb-1">
              <Zap className={`w-4 h-4 ${isDeployed ? 'text-green-600' : 'text-amber-600'}`} />
              <p className="font-semibold text-sm"
                style={{ color: isDeployed ? '#16a34a' : '#d97706' }}>
                {isDeployed ? 'Y8Settings Contract Deployed' : 'Deploy Y8Settings Contract'}
              </p>
            </div>
            {isDeployed ? (
              <div className="flex items-center gap-2">
                <code className="text-xs text-green-700 bg-green-100 px-2 py-0.5 rounded">
                  {contractAddr.slice(0, 10)}…{contractAddr.slice(-8)}
                </code>
                <a
                  href={`https://sepolia.basescan.org/address/${contractAddr}`}
                  target="_blank" rel="noreferrer"
                  className="text-green-600 hover:text-green-800"
                >
                  <ExternalLink className="w-3.5 h-3.5" />
                </a>
              </div>
            ) : (
              <p className="text-xs text-amber-700 mt-0.5">
                Deploy once to Base Sepolia — settings persist on-chain forever.
              </p>
            )}
          </div>
          {!isDeployed && (
            <button
              onClick={handleDeploy}
              disabled={!isConnected || isDeploying}
              className="flex items-center gap-2 px-5 py-2.5 bg-[#f5c518] hover:bg-[#e6b800] text-slate-900 font-semibold rounded-xl text-sm transition-colors disabled:opacity-50 shadow-sm"
            >
              {isDeploying ? (
                <><RefreshCw className="w-4 h-4 animate-spin" /> Deploying…</>
              ) : (
                <><Rocket className="w-4 h-4" /> Deploy to Base Sepolia</>
              )}
            </button>
          )}
        </div>
        {!isConnected && (
          <p className="text-xs text-amber-700 mt-3">⚠ Connect your wallet to deploy or save settings.</p>
        )}
        {needsSepolia && isConnected && (
          <p className="text-xs text-amber-700 mt-3">⚠ Switch to Base Sepolia to deploy/save settings.</p>
        )}
      </div>

      {/* Settings Grid */}
      <div>
        <p className="text-sm font-semibold text-slate-500 uppercase tracking-widest mb-4">Settings</p>
        <div className="grid grid-cols-1 md:grid-cols-2 gap-4">
          <ToggleCard
            icon={<MapPin className="w-5 h-5" />}
            label="GPS Location"
            description="Share your location for rideshare dispatch and entropy collection."
            value={localSettings.gpsEnabled}
            onChange={v => handleToggle('gpsEnabled', v)}
            isPending={isUpdating}
            color="#f5c518"
          />
          <ToggleCard
            icon={<Car className="w-5 h-5" />}
            label="Active Driver"
            description="Appear as available for rideshare pickups in your area."
            value={localSettings.activeDriver}
            onChange={v => handleToggle('activeDriver', v)}
            isPending={isUpdating}
            color="#22c55e"
          />
          <ToggleCard
            icon={<Wifi className="w-5 h-5" />}
            label="Online Status"
            description="Show as online and available to other Y8 users."
            value={localSettings.onlineStatus}
            onChange={v => handleToggle('onlineStatus', v)}
            isPending={isUpdating}
            color="#3b82f6"
          />
          <ToggleCard
            icon={<Bell className="w-5 h-5" />}
            label="Notifications"
            description="Receive push notifications for agent dispatches and updates."
            value={localSettings.notifications}
            onChange={v => handleToggle('notifications', v)}
            isPending={isUpdating}
            color="#8b5cf6"
          />
          <ToggleCard
            icon={<EyeOff className="w-5 h-5" />}
            label="Privacy Mode"
            description="Hide your profile from public discovery and agent matching."
            value={localSettings.privacyMode}
            onChange={v => handleToggle('privacyMode', v)}
            isPending={isUpdating}
            color="#ef4444"
          />
          <ToggleCard
            icon={<Moon className="w-5 h-5" />}
            label="Dark Mode"
            description="Theme preference stored permanently on-chain."
            value={localSettings.darkMode}
            onChange={v => handleToggle('darkMode', v)}
            isPending={isUpdating}
            color="#64748b"
          />
        </div>
      </div>

      {/* Proof of Entropy link */}
      <Link href="/space/entropy"
        className="flex items-center justify-between bg-gradient-to-r from-indigo-900 to-slate-900 text-white rounded-2xl p-5 hover:from-indigo-800 transition-all group"
      >
        <div className="flex items-center gap-3">
          <div className="w-10 h-10 bg-indigo-500/20 rounded-xl flex items-center justify-center">
            <Zap className="w-5 h-5 text-indigo-300" />
          </div>
          <div>
            <p className="font-semibold">Proof of Entropy</p>
            <p className="text-xs text-indigo-300">Mint on-chain proofs from device telemetry</p>
          </div>
        </div>
        <ChevronRight className="w-5 h-5 text-indigo-400 group-hover:translate-x-1 transition-transform" />
      </Link>
    </div>
  );
}
